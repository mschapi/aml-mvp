import { build } from 'esbuild';
import { strict as assert } from 'node:assert';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

await build({ entryPoints: ['src/demo.ts'], outfile: 'node_modules/.cache/aml-demo-test.mjs', bundle: true, platform: 'node', format: 'esm', packages: 'external' });
const cache = new Map();
globalThis.localStorage = { getItem: k => cache.get(k) ?? null, setItem: (k, v) => cache.set(k, v) };
const { demoRequest: api } = await import(pathToFileURL(resolve('node_modules/.cache/aml-demo-test.mjs')));
const initial = await api('/bootstrap', 'ana');
assert.equal(initial.transaction_count, 6000);
assert.equal(initial.cases.length, 18);
assert.equal(initial.data_end, new Date().toISOString().slice(0, 10));
await assert.rejects(api('/monitor/run', 'ana', {}), /supervisor/);
const next = await api('/cases/next', 'ana', {});
assert.equal(next.status, 'Asignada');
await api(`/cases/${next.id}/action`, 'ana', { action: 'transition', target: 'En analisis', reason: 'Prueba del flujo' });
assert.equal((await api('/bootstrap', 'ana')).cases.find(c => c.id === next.id).status, 'En analisis');
await assert.rejects(api('/rules', 'ana', { name: 'Invalida', business: initial.businesses[0], severity: 'Alto', window_days: 30, conditions: [{ field: '__proto__', operator: '==', value: 1 }] }), /catalogo/);
const rule = await api('/rules', 'ana', { name: 'Regla demo verificada', business: initial.businesses[0], severity: 'Alto', window_days: 30, conditions: [{ field: 'volume', operator: '>', value: 0 }] });
await assert.rejects(api(`/rules/${rule.id}/action`, 'ana', { action: 'submit', reason: 'Prueba solicitud' }), /Simula/);
const sim = await api(`/rules/${rule.id}/simulate`, 'ana', { start_date: initial.data_start, end_date: initial.data_end });
assert.equal(sim.matched_entities, 8);
await api(`/rules/${rule.id}/action`, 'ana', { action: 'submit', reason: 'Prueba solicitud' });
await api(`/rules/${rule.id}/action`, 'sofia', { action: 'approve', reason: 'Revision independiente' });
await api('/monitor/run', 'sofia', {});
assert.equal((await api('/monitor/run', 'sofia', {})).generated, 0);
assert.ok((await api('/screening/run', 'sofia', {})).new_matches > 0);
assert.equal((await api('/screening/run', 'sofia', {})).new_matches, 0);
await api('/lists/revise', 'sofia', { target: 'L1' });
assert.equal((await api('/screening/run', 'sofia', {})).new_matches, 1);
await assert.rejects(api('/config', 'sofia', { ...initial.config, weights: { ...initial.config.weights, behavior_risk: 0 } }, 'PUT'), /Pesos/);
assert.equal((await api('/segments/recalculate', 'sofia', {})).count, 32);
assert.ok((await api('/entities/E001', 'ana')).related.length > 0);
assert.ok(cache.size > 0);
console.log('PASS: seed, permissions, persistence, case workflow, catalog validation, simulation, approval, monitor idempotency, screening versions and segmentation');
